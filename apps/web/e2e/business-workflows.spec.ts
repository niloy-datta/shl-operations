test("administrator password recovery revokes an existing staff session", async ({ page }) => {
  const api = await apiFor();
  const username = "e2e_recovery_" + Date.now(), password = "Synthetic-old-password-" + Date.now();
  await json(api, "/api/enterprise/staff", "POST", { username, password, role: "BD" });
  const login = await api.post("/api/auth/login", { data: { username, password } });
  expect(login.status()).toBe(200);
  const oldCookie = login.headers()["set-cookie"].split(";", 1)[0];
  await useRole(page);
  await page.goto("/workspace/enterprise/staff");
  const row = page.getByRole("row").filter({ hasText: username });
  const reset = row.getByRole("button", { name: "Reset password", exact: true });
  await reset.scrollIntoViewIfNeeded();
  expect(await reset.evaluate(button => {
    const cell = button.closest("td")!.getBoundingClientRect(), box = button.getBoundingClientRect();
    return box.left >= cell.left && box.right <= cell.right && box.top >= cell.top && box.bottom <= cell.bottom;
  }), "Staff actions must fit inside their cell without clipping").toBe(true);
  await reset.click();
  const dialog = page.getByRole("dialog", { name: "Reset staff password" });
  await dialog.getByLabel("Your administrator password").fill(accounts().ADMIN.password);
  const replacement = "Synthetic-replacement-password-" + Date.now();
  await dialog.getByLabel("New temporary password (16–128 characters)").fill(replacement);
  await dialog.getByLabel("Confirm temporary password").fill(replacement);
  await dialog.getByRole("button", { name: "Confirm password reset" }).click();
  await expect(dialog).toHaveCount(0);
  expect((await api.get("/api/auth/mfa/status", { headers: { cookie: oldCookie } })).status()).toBe(401);
  expect((await api.post("/api/auth/login", { data: { username, password } })).status()).toBe(401);
  expect((await api.post("/api/auth/login", { data: { username, password: replacement } })).status()).toBe(200);
  await api.dispose();
});
