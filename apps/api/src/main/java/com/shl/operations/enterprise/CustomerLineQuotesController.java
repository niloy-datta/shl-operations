package com.shl.operations.enterprise;

import jakarta.validation.Valid;
import jakarta.validation.constraints.*;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.LocalDate;
import java.util.*;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

/**
 * Quote approval isolated from legacy single-header orders.
 * No new order, payment or document is generated by this controller.
 */
@RestController
@RequestMapping("/api/commerce/line-quotes")
@PreAuthorize("hasAnyRole('ADMIN','MANAGEMENT','BD','SOURCING')")
public class CustomerLineQuotesController {
    private final JdbcTemplate db;
    private final AuditService audit;
    public CustomerLineQuotesController(JdbcTemplate db, AuditService audit) {
        this.db=db;this.audit=audit;
    }

    public record SelectedLine(@NotNull UUID itemId,@NotNull UUID sourceRevisionId,
        @NotNull @DecimalMin("0.0001") @Digits(integer=14,fraction=4) BigDecimal sellUnitPrice) {}
    public record Create(@NotNull UUID rfqId, LocalDate validUntil,
        @NotEmpty @Size(max=50) List<@Valid SelectedLine> items) {}
    public record Review(@NotBlank @Pattern(regexp="APPROVED|REJECTED") String decision,
        @Size(max=1000) String notes) {}
    public record QuoteDetails(Map<String,Object> quote,List<Map<String,Object>> lines) {}

    private static ResponseStatusException blocked(String message) {
        return new ResponseStatusException(HttpStatus.CONFLICT,message);
    }
    private static BigDecimal money(BigDecimal value) {
        return value.setScale(2,RoundingMode.HALF_UP);
    }
    private static String actorName(AuditService a) { return a.actor(); }

    private Map<String,Object> readQuote(UUID id) {
        return db.queryForList("SELECT * FROM customer_line_quotes WHERE id=?",id)
            .stream().findFirst().orElseThrow(()->
                new ResponseStatusException(HttpStatus.NOT_FOUND,"Customer line quote not found"));
    }

    @GetMapping
    public List<Map<String,Object>> list(@RequestParam UUID rfqId) {
        return db.queryForList("""
            SELECT * FROM customer_line_quotes WHERE rfq_id=?
            ORDER BY version DESC LIMIT 100
            """,rfqId);
    }

    @GetMapping("/{quoteId}")
    public QuoteDetails detail(@PathVariable UUID quoteId) {
        Map<String,Object> quote=readQuote(quoteId);
        var rows=db.queryForList("""
            SELECT qli.*, i.line_number, s.name AS supplier_name
            FROM customer_line_quote_items qli
            JOIN rfq_line_items i ON i.id=qli.rfq_item_id
            JOIN suppliers s ON s.id=qli.supplier_id
            WHERE qli.quote_id=? ORDER BY i.line_number
            """,quoteId);
        return new QuoteDetails(quote,rows);
    }

    private void checkCurrentRevisions(UUID rfqId,UUID quoteId) {
        Integer stale=db.queryForObject("""
            SELECT count(*) FROM customer_line_quote_items qli
            JOIN rfq_line_offer_revisions p ON p.id=qli.source_revision_id
            JOIN customer_line_quotes q ON q.id=qli.quote_id
            WHERE q.id=? AND q.rfq_id=?
              AND EXISTS (SELECT 1 FROM rfq_line_offer_revisions latest
                          WHERE latest.item_id=p.item_id
                            AND latest.supplier_id=p.supplier_id
                            AND latest.revision_number>p.revision_number)
            """,Integer.class,quoteId,rfqId);
        if(stale!=null && stale>0) throw blocked(
            "One or more supplier prices have newer revisions; create a new customer quote version");
    }

    @PostMapping
    @PreAuthorize("hasAnyRole('ADMIN','MANAGEMENT','BD')")
    @ResponseStatus(HttpStatus.CREATED)
    @Transactional
    public QuoteDetails create(@Valid @RequestBody Create input) {
        Map<String,Object> rfq=db.queryForList("""
            SELECT id,status,currency FROM rfqs WHERE id=? FOR UPDATE
            """,input.rfqId()).stream().findFirst().orElseThrow(()->
                new ResponseStatusException(HttpStatus.NOT_FOUND,"RFQ not found"));
        if(!"SOURCING".equals(rfq.get("status")))
            throw blocked("Create draft quotations only while sourcing");
        if(input.validUntil()!=null && input.validUntil().isBefore(LocalDate.now()))
            throw blocked("Quotation validity cannot already have expired");
        Long legacy=db.queryForObject("""
            SELECT count(*) FROM supplier_offers WHERE rfq_id=?
            """,Long.class,input.rfqId());
        if(legacy!=null && legacy>0) throw blocked(
            "Legacy aggregate supplier offers cannot be used for line-aware customer quotes");
        Long approved=db.queryForObject("""
            SELECT count(*) FROM customer_line_quotes WHERE rfq_id=? AND status='APPROVED'
            """,Long.class,input.rfqId());
        if(approved!=null && approved>0)
            throw blocked("Approved customer quotation already exists; amendments need a reviewed change order");

        List<Map<String,Object>> requirements=db.queryForList("""
            SELECT id,product_name,quantity,unit FROM rfq_line_items
            WHERE rfq_id=? ORDER BY line_number
            """,input.rfqId());
        if(requirements.isEmpty() || requirements.size()!=input.items().size())
            throw blocked("Select exactly one supplier revision for every RFQ requirement line");
        var requirementMap=new HashMap<UUID,Map<String,Object>>();
        for(var row:requirements)requirementMap.put((UUID)row.get("id"),row);
        var seen=new HashSet<UUID>();
        BigDecimal totalCost=BigDecimal.ZERO,totalSell=BigDecimal.ZERO;
        record Line(UUID itemId,UUID revisionId,UUID supplierId,String product,
            String unit,BigDecimal quantity,BigDecimal cost,BigDecimal sell,
            BigDecimal lineCost,BigDecimal lineSell){}
        var verified=new ArrayList<Line>();
        for(var selected:input.items()) {
            if(!seen.add(selected.itemId()) || !requirementMap.containsKey(selected.itemId()))
                throw blocked("Duplicate or foreign RFQ requirement line");
            Map<String,Object> revision=db.queryForList("""
                SELECT id,item_id,supplier_id,unit_price,moq,revision_number
                FROM rfq_line_offer_revisions WHERE id=? AND rfq_id=?
                """,selected.sourceRevisionId(),input.rfqId())
                .stream().findFirst().orElseThrow(()->
                    blocked("Supplier revision does not belong to this RFQ"));
            if(!selected.itemId().equals(revision.get("item_id")))
                throw blocked("Supplier revision is linked to a different product");
            Integer newer=db.queryForObject("""
                SELECT count(*) FROM rfq_line_offer_revisions
                WHERE item_id=? AND supplier_id=? AND revision_number>?
                """,Integer.class,selected.itemId(),revision.get("supplier_id"),
                revision.get("revision_number"));
            if(newer!=null && newer>0)
                throw blocked("Select the supplier's latest price revision for each line");
            Map<String,Object> item=requirementMap.get(selected.itemId());
            BigDecimal quantity=(BigDecimal)item.get("quantity");
            if(((BigDecimal)revision.get("moq")).compareTo(quantity)>0)
                throw blocked("Supplier MOQ exceeds requested quantity; separate approval required");
            BigDecimal cost=(BigDecimal)revision.get("unit_price");
            if(selected.sellUnitPrice().compareTo(cost)<0)
                throw blocked("Negative gross contribution is not permitted without reviewed exception");
            BigDecimal lineCost=money(quantity.multiply(cost));
            BigDecimal lineSell=money(quantity.multiply(selected.sellUnitPrice()));
            if(lineCost.signum()<=0 || lineSell.signum()<=0)
                throw blocked("Amounts below currency precision cannot be quoted");
            totalCost=totalCost.add(lineCost);totalSell=totalSell.add(lineSell);
            verified.add(new Line(selected.itemId(),selected.sourceRevisionId(),
                (UUID)revision.get("supplier_id"),(String)item.get("product_name"),
                (String)item.get("unit"),quantity,cost,selected.sellUnitPrice(),
                lineCost,lineSell));
        }
        if(!seen.equals(requirementMap.keySet()))
            throw blocked("Every RFQ line must be priced once");

        Integer version=db.queryForObject("""
            SELECT COALESCE(MAX(version),0)+1 FROM customer_line_quotes WHERE rfq_id=?
            """,Integer.class,input.rfqId());
        if(version==null || version>10000) throw blocked("Version limit reached");
        UUID quoteId=UUID.randomUUID();
        db.update("""
            INSERT INTO customer_line_quotes
              (id,rfq_id,version,currency,valid_until,total_cost,total_sell,
               gross_contribution,created_by)
            VALUES(?,?,?,?,?,?,?,?,?)
            """,quoteId,input.rfqId(),version,rfq.get("currency"),input.validUntil(),
            totalCost,totalSell,totalSell.subtract(totalCost),actorName(audit));
        for(var line:verified)db.update("""
            INSERT INTO customer_line_quote_items
            (id,quote_id,rfq_item_id,source_revision_id,supplier_id,product_name,
             unit,quantity,source_unit_cost,sell_unit_price,cost_total,sell_total)
            VALUES(?,?,?,?,?,?,?,?,?,?,?,?)
            """,UUID.randomUUID(),quoteId,line.itemId(),line.revisionId(),
            line.supplierId(),line.product(),line.unit(),line.quantity(),
            line.cost(),line.sell(),line.lineCost(),line.lineSell());
        audit.log("CREATED","LINE_QUOTE",quoteId,
            "RFQ "+input.rfqId()+" version "+version+"; provisional cost/sell");
        return detail(quoteId);
    }

    @PostMapping("/{quoteId}/submit")
    @PreAuthorize("hasAnyRole('ADMIN','MANAGEMENT','BD')")
    @Transactional
    public QuoteDetails submit(@PathVariable UUID quoteId) {
        // Lock order matches create(): RFQ first, then quote, to avoid deadlocks.
        Map<String,Object> initial=readQuote(quoteId);
        UUID rfqId=(UUID)initial.get("rfq_id");
        Map<String,Object> rfq=db.queryForMap(
            "SELECT status FROM rfqs WHERE id=? FOR UPDATE",rfqId);
        if(!"SOURCING".equals(rfq.get("status")))
            throw blocked("RFQ no longer in sourcing");
        Map<String,Object> quote=db.queryForMap(
            "SELECT * FROM customer_line_quotes WHERE id=? FOR UPDATE",quoteId);
        if(!"DRAFT".equals(quote.get("status"))) throw blocked("Only drafts can be submitted");
        if(!actorName(audit).equals(quote.get("created_by")))
            throw blocked("Only the draft owner can submit a quote");
        var until=quote.get("valid_until");
        if(until!=null && ((java.sql.Date)until).toLocalDate().isBefore(LocalDate.now()))
            throw blocked("Expired customer quotation");
        checkCurrentRevisions(rfqId,quoteId);
        Integer active=db.queryForObject("""
            SELECT count(*) FROM customer_line_quotes
            WHERE rfq_id=? AND status IN ('SUBMITTED','APPROVED') AND id<>?
            """,Integer.class,rfqId,quoteId);
        if(active!=null && active>0)throw blocked(
            "Another customer quotation is already submitted or approved");
        db.update("UPDATE customer_line_quotes SET status='SUBMITTED',updated_at=now() WHERE id=?",
            quoteId);
        audit.log("SUBMITTED","LINE_QUOTE",quoteId,"Submitted for independent review");
        return detail(quoteId);
    }

    @PostMapping("/{quoteId}/review")
    @PreAuthorize("hasAnyRole('ADMIN','MANAGEMENT')")
    @Transactional
    public QuoteDetails review(@PathVariable UUID quoteId,@Valid @RequestBody Review input) {
        Map<String,Object> initial=readQuote(quoteId);
        UUID rfqId=(UUID)initial.get("rfq_id");
        Map<String,Object> rfq=db.queryForMap(
            "SELECT status FROM rfqs WHERE id=? FOR UPDATE",rfqId);
        if(!"SOURCING".equals(rfq.get("status")))
            throw blocked("RFQ no longer in sourcing");
        Map<String,Object> quote=db.queryForMap(
            "SELECT * FROM customer_line_quotes WHERE id=? FOR UPDATE",quoteId);
        if(!"SUBMITTED".equals(quote.get("status")))
            throw blocked("Only submitted customer quotes can be reviewed");
        if(actorName(audit).equals(quote.get("created_by")))
            throw blocked("Four-eyes rule: the creator cannot approve or reject own quotation");
        if("APPROVED".equals(input.decision())) {
            var until=quote.get("valid_until");
            if(until!=null && ((java.sql.Date)until).toLocalDate().isBefore(LocalDate.now()))
                throw blocked("Expired customer quotation");
            checkCurrentRevisions(rfqId,quoteId);
        }
        db.update("""
            UPDATE customer_line_quotes
            SET status=?,reviewed_by=?,review_notes=?,reviewed_at=now(),updated_at=now()
            WHERE id=?
            """,input.decision(),actorName(audit),
            input.notes()==null ? null : input.notes().trim(),quoteId);
        audit.log("REVIEWED","LINE_QUOTE",quoteId,
            input.decision()+" by independent reviewer");
        return detail(quoteId);
    }
}
